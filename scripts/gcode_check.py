def manifest_rows() -> list[dict]:
    with open(MANIFEST, encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def run(summary: bool, check: bool) -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    txt = plate20_text()
    if check:
        if not PLATE.exists() or PLATE.read_bytes() != txt.encode("utf-8"):
            print("오류: plate20.gcode가 다시 만든 것과 다름", file=sys.stderr)
            return 1
    else:
        PLATE.write_bytes(txt.encode("utf-8"))
    targets = []
    for m in manifest_rows():
        targets.append((m["이름"], ROOT / m["로컬경로"], m["sha256"], "public_gcode"))
    all_rows, details = [], {}
    for name, p, sm, role in targets:
        if not p.exists():
            print(f"오류: {p} 없음", file=sys.stderr)
            return 1
        chk, rows, det = check_file(name, p, sm, role)
        details[name] = (chk, rows, det)
        if summary or not check:
            print("CHECK " + json.dumps(chk, ensure_ascii=False))
        for n, item, v, g in rows:
            all_rows.append({"항목": f"{n:02d} {item}", "파일": name, "값": v, "근거": g})
    # plate20 기본 값 (시나리오용 시편, 점검표에는 넣지 않음)
    rp = parse_file(PLATE)
    bp = object_bbox(rp)
    print("PLATE " + json.dumps(dict(sha256=sha256_of(PLATE), layers=len(rp.layers), unknown=rp.summary()["unknown"],
                                     bbox_w_mm=round(bp["W"], 3), bbox_h_mm=round(bp["H"], 3),
                                     passes=scan_cases(bp["W"], bp["H"])["0"]["passes"]), ensure_ascii=False))
    if check:
        with open(CSV_OUT, encoding="utf-8") as fh:
            old = list(csv.DictReader(fh))
        if old != all_rows:
            print("오류: 점검표.csv가 다시 계산한 것과 다름", file=sys.stderr)
            return 1
        print("CHECK-MODE 통과: plate20 · 점검표.csv 같음")
        return 0
    with open(CSV_OUT, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["항목", "파일", "값", "근거"])
        w.writeheader()
        w.writerows(all_rows)
    RES_DIR.mkdir(parents=True, exist_ok=True)
    names = list(details)
    md = ["| # | 항목 | " + " | ".join(names) + " |", "|---|---|" + "---|" * len(names)]
    for i in range(24):
        n, item = details[names[0]][1][i][:2]
        cells = [f"{details[k][1][i][2]} ({details[k][1][i][3]})".replace("|", "/") for k in names]
        md.append(f"| {n} | {item} | " + " | ".join(cells) + " |")
    md.append("")
    md.append("## 명령 종류별 개수")
    for k in names:
        det = details[k][2]
        md.append(f"### {k}: " + ", ".join(f"{c} {v}" for c, v in sorted(det['cls'].items())))
        md.append(", ".join(f"{w} {c} (첫 줄 {det['first'][w]})" for w, c in det["cmd"].most_common()))
        md.append("klipper: " + json.dumps(det["issues"], ensure_ascii=False))
        md.append("cases: " + json.dumps(det["cases"], ensure_ascii=False))
        md.append("bbox: " + json.dumps(det["bbox"], ensure_ascii=False) + " top: " + json.dumps({a: b for a, b in det['top'].items() if a != 'type_names'}, ensure_ascii=False))
    (RES_DIR / "점검표_표.md").write_text("\n".join(md), encoding="utf-8")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--summary", action="store_true", help="CHECK 줄만 출력 (산출물도 다시 씀)")
    ap.add_argument("--check", action="store_true", help="기존 산출물 재검사 (쓰지 않음)")
    a = ap.parse_args(argv)
    return run(a.summary, a.check)


if __name__ == "__main__":
    sys.exit(main())
