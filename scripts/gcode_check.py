_WORD = re.compile(r"^([A-Za-z_][A-Za-z0-9_.]*)")


def sha256_of(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


# ---- plate20 (§6.9) ---------------------------------------------------------
def plate20_text() -> str:
    """20 × 20 mm, 선 간격 0.4 지그재그, 선폭 0.4, 층 0.2 × 10. 같은 입력이면 같은 바이트."""
    fil_area = math.pi * (1.75 / 2) ** 2
    e_per_mm = 0.4 * 0.2 / fil_area
    L = ["; 스크립트가 만든 시험용 평판, 실제 슬라이서 출력 아님 (T5 plate20, scripts/gcode_check.py)",
         "; generated by cvlab-T5-plate20 1",
         "; gcode_flavor = klipper", "; nozzle_diameter = 0.4", "; line_width = 0.4",
         "; layer_height = 0.2", "; initial_layer_print_height = 0.2", "; filament_diameter = 1.75",
         "; total layers count = 10",
         "G21", "G90", "M83", "G92 E0"]
    ys = [round(165.2 + 0.4 * i, 4) for i in range(50)]
    for k in range(10):
        z = round(0.2 * (k + 1), 4)
        L += [";LAYER_CHANGE", f";Z:{z:.1f}", ";HEIGHT:0.2", f"G1 Z{z:.1f} F600",
              f"G0 X165.2 Y{ys[0]:.1f} F6000", ";TYPE:Solid infill"]
        x_at = 165.2
        for i, y in enumerate(ys):
            if i > 0:
                L.append(f"G1 X{x_at:.1f} Y{y:.1f} E{0.4 * e_per_mm:.5f} F1800")
            x_to = 184.8 if x_at < 175 else 165.2
            L.append(f"G1 X{x_to:.1f} Y{y:.1f} E{19.6 * e_per_mm:.5f} F1800")
            x_at = x_to
    L += ["G1 Z12.0 F600", "M84", ""]
    return "\n".join(L)


# ---- 계산 -------------------------------------------------------------------
def n_pass(size_mm: float, span_mm: float, o: float = OVERLAP_MM) -> int:
    num = int(np.rint((size_mm - o) * 1e6))
    den = int(np.rint((span_mm - o) * 1e6))
    if num <= 0:
        return 1
    return max(1, -(-num // den))


def object_bbox(r) -> dict:
    e = r.extrusions()
    w = segment_widths(r, r.params or GCodeParams())
    m = ~e["type"].isin(EXCLUDED).to_numpy()
    eo, wo = e[m], w[m]
    xs = np.concatenate([eo.x0_mm, eo.x1_mm]); ys = np.concatenate([eo.y0_mm, eo.y1_mm])
    half = float(np.max(wo)) / 2.0
    b = dict(xmin=float(xs.min()) - half, xmax=float(xs.max()) + half,
             ymin=float(ys.min()) - half, ymax=float(ys.max()) + half, half_w=half)
    b["W"], b["H"] = b["xmax"] - b["xmin"], b["ymax"] - b["ymin"]
    return b


def scan_cases(W: float, H: float) -> dict:
    out = {}
    for name, (a, b, L) in {"0": (W, H, SCAN_LEN_MM), "rot90": (H, W, SCAN_LEN_MM), "extend": (W, H, None)}.items():
        nx = n_pass(a, FOV_MM)
        if L is None:
            ny, Ls = 1, b
        else:
            ny, Ls = n_pass(b, L), L
        f1 = nx * ny * (LEAD_IN + Ls) / SPEED + (LEAD_IN + REF_LEN) / SPEED + MOVE_S
        f2 = nx * ny * Ls / SPEED
        out[name] = dict(n_x=nx, n_y=ny, passes=nx * ny, scan_len_mm=round(Ls, 3),
                         f1_s=round(f1, 2), f2_s=round(f2, 2))
    return out


def top_info(r, b) -> dict:
    """층마다 물체 윗면 높이 폭, 심도 넘는 층 수 (T4a §6과 같은 뜻: 물체 = 꼭대기 종류가 제외 종류 아님)."""
    grid = make_grid(b["xmin"], b["xmax"], b["ymin"], b["ymax"], 0.02, 1.0)
    ref = build_reference(r, grid=grid)
    exc = {i for i, t in enumerate(ref.type_names) if t in EXCLUDED}
    top = np.full((grid["ny"], grid["nx"]), -1, np.int32)
    tc = np.full(top.shape, -1, np.int16)
    spans, first = [None] * ref.n_layers, None
    # 꼭대기 층 · 종류를 차례로 덮어 한 번에 구함 (type_at(n)을 층마다 부르면 층 수 제곱)
    tcodes = ref._type_codes  # 같은 패키지의 저장 형식 (읽기만, 공개 type_at과 같은 값)
    depth_layers, max_span = 0, 0.0
    for n in range(ref.n_layers):
        fp = ref.footprint(n)
        top[fp] = n
        flat = tc.ravel()
        flat[np.flatnonzero(fp.ravel())] = tcodes[n]
        obj = (top >= 0) & ~np.isin(tc, list(exc)) if exc else (top >= 0)
        if not obj.any():
            spans[n] = 0.0
            continue
        z = ref.z_layers[top[obj]]
        s = float(z.max() - z.min())
        spans[n] = s
        if int(np.rint(s * 1e6)) > int(np.rint(DEPTH_MM * 1e6)):
            depth_layers += 1
            if first is None:
                first = n
        max_span = max(max_span, s)
    return dict(depth_layers=depth_layers, first_depth_layer=first, max_span_mm=round(max_span, 4),
                grid=f"{grid['ny']} x {grid['nx']}", type_names=ref.type_names)


def count_commands(path: Path) -> tuple[Counter, dict]:
    cnt, first = Counter(), {}
    with open(path, encoding="utf-8", errors="replace") as fh:
        for i, raw in enumerate(fh, 1):
            s = raw.split(";", 1)[0].strip()
            s = re.sub(r"^N\d+\s+", "", s)
            s = s.split("*", 1)[0].strip()
            if not s:
                continue
            m = _WORD.match(s)
            if not m:
                continue
            w = m.group(1).upper()
            mm = re.match(r"^([GMT])0*(\d+(?:\.\d+)?)$", w)
            if mm:
                w = mm.group(1) + mm.group(2)
            cnt[w] += 1
            first.setdefault(w, i)
    return cnt, first


def cmd_class(w: str) -> str:
    if re.fullmatch(r"G\d+(\.\d+)?", w):
        return "G"
    if re.fullmatch(r"M\d+(\.\d+)?", w):
        return "M"
    if re.fullmatch(r"T\d+", w):
        return "T"
    return "매크로"


def find_line(lines: list[str], pat: str, start: int = 0) -> int | None:
    rx = re.compile(pat)
    for i in range(start, len(lines)):
        if rx.search(lines[i]):
            return i + 1
    return None


def find_all(lines, pat):
    rx = re.compile(pat)
    return [i + 1 for i, l in enumerate(lines) if rx.search(l)]


def hval(lines, key):
    n = find_line(lines, r"^;\s*" + re.escape(key) + r"\s*=")
    if n is None:
        return None, None
    return lines[n - 1].split("=", 1)[1].strip(), n


