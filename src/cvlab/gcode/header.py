"""슬라이서 머리말·설정 블록 읽기 (GC6).

못 찾은 값은 None. 경고는 parse_text가 남긴다.
"""
from __future__ import annotations

import re

_KV_RE = re.compile(r"^;\s*([A-Za-z_][\w \[\]\-]*?)\s*(?:=|:)\s*(.*?)\s*$")
_GEN_BY_RE = re.compile(r"^;\s*generated by\s+(\S+)\s+(\S+)", re.I)
_GEN_WITH_RE = re.compile(r"^;\s*Generated with\s+(\S+)\s+(\S+)", re.I)
_BAMBU_RE = re.compile(r"^;\s*(BambuStudio|OrcaSlicer)\s+([\d.]+)\s*$")

# 방언 원문 → 명세 meta.gcode_flavor
FLAVOR_MAP = {
    "marlin": "marlin", "marlin2": "marlin", "marlinlegacy": "marlin", "marlinfirmware": "marlin",
    "klipper": "klipper",
    "reprap": "reprap", "reprapfirmware": "reprap", "rrf": "reprap", "reprapsprinter": "reprap",
}

# 선폭 키 (표준 경로 종류 → 슬라이서 키 후보, 앞쪽 우선)
WIDTH_KEYS = {
    "DEFAULT": ["line_width", "extrusion_width"],
    "WALL-OUTER": ["outer_wall_line_width", "external_perimeter_extrusion_width"],
    "WALL-INNER": ["inner_wall_line_width", "perimeter_extrusion_width"],
    "FILL": ["sparse_infill_line_width", "infill_extrusion_width"],
    "SKIN": ["internal_solid_infill_line_width", "solid_infill_extrusion_width"],
    "SKIN-TOP": ["top_surface_line_width", "top_infill_extrusion_width"],
    "SUPPORT": ["support_line_width", "support_material_extrusion_width"],
    "FIRST_LAYER": ["initial_layer_line_width", "first_layer_extrusion_width"],
}


def map_flavor(raw: str | None) -> str | None:
    if raw is None:
        return None
    key = re.sub(r"[\s_\-]", "", raw.strip().lower())
    if key in FLAVOR_MAP:
        return FLAVOR_MAP[key]
    if key.startswith("marlin"):
        return "marlin"
    if key.startswith("reprap"):
        return "reprap"
    return "other"


def _first_num(v: str | None) -> float | None:
    """'0.4,0.4' → 0.4. '%'·0·빈칸은 None (상대값·자동)."""
    if v is None:
        return None
    first = v.split(",")[0].strip().strip('"')
    if not first or first.endswith("%"):
        return None
    try:
        x = float(first)
    except ValueError:
        return None
    return x if x > 0 else None


def _sum_nums(v: str) -> float | None:
    tot, ok = 0.0, False
    for part in v.split(","):
        try:
            tot += float(part.strip())
            ok = True
        except ValueError:
            pass
    return tot if ok else None


def parse_header(lines: list[str]) -> dict:
    kv: dict = {}
    slicer_name = slicer_version = None
    for raw in lines:
        s = raw.strip()
        if not s.startswith(";"):
            continue
        if slicer_name is None:
            m = _GEN_BY_RE.match(s) or _GEN_WITH_RE.match(s) or _BAMBU_RE.match(s)
            if m:
                slicer_name, slicer_version = m.group(1), m.group(2)
                continue
        m = _KV_RE.match(s)
        if m:
            k = m.group(1).strip().lower()
            kv.setdefault(k, m.group(2))

    flavor_raw = kv.get("gcode_flavor") or kv.get("flavor")
    layers_declared = None
    layer_keys_seen = {}
    for k in ("total layers count", "layer_count", "total layer number"):
        if k in kv:
            try:
                layer_keys_seen[k] = int(float(kv[k].split(",")[0]))
            except ValueError:
                pass
    for k in ("total layers count", "layer_count", "total layer number"):
        if k in layer_keys_seen:
            layers_declared = layer_keys_seen[k]
            break

    filament_mm = None
    if "filament used [mm]" in kv:
        filament_mm = _sum_nums(kv["filament used [mm]"])
    elif "filament used" in kv:
        v = kv["filament used"].strip()
        m = re.match(r"([\d.]+)\s*m\b", v)
        if m:
            filament_mm = float(m.group(1)) * 1000.0
        else:
            mm = re.match(r"([\d.]+)\s*mm\b", v)
            if mm:
                filament_mm = float(mm.group(1))

    widths = {}
    for t, keys in WIDTH_KEYS.items():
        for k in keys:
            v = _first_num(kv.get(k))
            if v is not None:
                widths[t] = v
                break

    top_layers = None
    for k in ("top_shell_layers", "top_solid_layers", "top_layers"):
        if k in kv:
            try:
                top_layers = int(float(kv[k].split(",")[0]))
                break
            except ValueError:
                pass
    infill_angle = None
    for k in ("infill_direction", "fill_angle", "infill_angle"):
        if k in kv:
            infill_angle = _first_num(kv[k]) if kv[k].strip() not in ("0",) else 0.0
            if infill_angle is not None:
                break

    return {
        "slicer_name": slicer_name,
        "slicer_version": slicer_version,
        "flavor_raw": flavor_raw,
        "gcode_flavor": map_flavor(flavor_raw),
        "layers_declared": layers_declared,
        "layers_declared_all": layer_keys_seen,
        "filament_used_mm": filament_mm,
        "nozzle_dia_mm": _first_num(kv.get("nozzle_diameter")),
        "line_width_mm": widths.get("DEFAULT"),
        "line_widths": widths,
        "layer_h_mm": _first_num(kv.get("layer_height")),
        "first_layer_h_mm": _first_num(kv.get("first_layer_height") or kv.get("initial_layer_print_height")),
        "filament_d_mm": _first_num(kv.get("filament_diameter")),
        "top_layers": top_layers,
        "infill_angle_deg": infill_angle,
    }
